// 游戏中使用的二维位置。先使用简单结构体，便于课程前期理解。
struct Point { // 定义表示二维坐标的结构体。
    float x = 0.0f; // 保存水平方向坐标。
    float y = 0.0f; // 保存垂直方向坐标。
}; // 结构体定义结束。

// 矩形区域。实验二用水域矩形统一描述可活动范围，避免各处散落窗口尺寸。
struct Rect { // 定义表示矩形区域的结构体。
    float left = 0.0f; // 保存左边界坐标。
    float top = 0.0f; // 保存上边界坐标。
    float right = 0.0f; // 保存右边界坐标。
    float bottom = 0.0f; // 保存下边界坐标。
}; // 结构体定义结束。
